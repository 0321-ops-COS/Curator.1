"""Run Freebuff as a supervised builder inside tmux.

The runner owns four things:

* a fresh ``freebuff/<short-id>`` branch and a git worktree for the job,
* a tmux session with Freebuff inside that worktree,
* reading the pane output into the job log, and
* collecting the resulting diff, status and changed paths.

It never pushes unless ``approve_and_push`` is called after a human pressed
Approve, and that method refuses anything outside ``freebuff/*``.

Completion detection is deliberately conservative: Freebuff has no documented
machine-readable "done" signal here, so the runner waits until the worktree has
stopped changing for an idle window, the session exits, or the hard timeout is
reached. Every outcome is written to the job log.
"""

