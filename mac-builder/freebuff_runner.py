PUSH_GUARD_TEMPLATE = """#!/bin/bash
# Generated by mac-builder for one job. Defence in depth only: it makes an
# accidental or instructed `git push` outside the job's own prefix fail loudly.
# __ALLOWED_PREFIX__ is freebuff/ for a task job and dan/ for a self-build job.
set -u
real_git=__REAL_GIT__
saw_push=0
for a in "$@"; do
  [ "$a" = "push" ] && saw_push=1
done
if [ "$saw_push" = 0 ]; then
  exec "$real_git" "$@"
fi
for a in "$@"; do
  case "$a" in
    --force|--force-with-lease|--force-if-includes|--mirror|--all|--tags|--delete|-f)
      echo "mac-builder: blocked git flag $a" >&2
      exit 1
      ;;
  esac
done
current="$("$real_git" rev-parse --abbrev-ref HEAD 2>/dev/null || true)"
case "$current" in
  __ALLOWED_PREFIX__*) ;;
  *)
    echo "mac-builder: blocked git push from ${current:-unknown branch}; only __ALLOWED_PREFIX__* may be pushed" >&2
    exit 1
    ;;
esac
seen_push=0
positional=0
for a in "$@"; do
  if [ "$seen_push" = 0 ]; then
    [ "$a" = "push" ] && seen_push=1
    continue
  fi
  case "$a" in
    -*) continue ;;
  esac
  positional=$((positional + 1))
  # The first positional is the remote (origin, a URL, ...).
  [ "$positional" -eq 1 ] && continue
  case "$a" in
    *://*) continue ;;
    *:*) dest="${a#*:}" ;;
    *) dest="${a#+}" ;;
  esac
  dest="${dest#+}"
  [ -z "$dest" ] && dest="$a"
  case "$dest" in
    refs/heads/__ALLOWED_PREFIX__*|__ALLOWED_PREFIX__*) ;;
    *)
      echo "mac-builder: blocked push to $dest; only __ALLOWED_PREFIX__* may be pushed" >&2
      exit 1
      ;;
  esac
done
exec "$real_git" "$@"
"""


class FreebuffError(RuntimeError):
    """A Freebuff job could not be started, supervised or collected."""


def _snapshot_label(snapshot: str) -> str:
    """Short 'commit/digest' form for a message, never the full value."""
    head, _, digest = snapshot.partition(":")
    return f"{head[:7]}/{digest[:8]}"


@dataclass
class TaskEnvironment:
    branch: str
    worktree: Path
    session: str
    base_branch: str
    guard_dir: Path | None = None
    round: int = 0
    signature_at_start: str = ""
    # "task" (freebuff/*, the target checkout) or "dan" (dan/*, her own code).
    kind: str = "task"


@dataclass
class ChangeSet:
    diff: str
    diff_lines: int
    changed_paths: list[str] = field(default_factory=list)
    status: str = ""
    head: str = ""
    # HEAD plus a digest of the staged change set; see GitRepo.snapshot.
    snapshot: str = ""

    @property
    def empty(self) -> bool:
        return not self.changed_paths and self.diff_lines == 0


@dataclass
class CommandResult:
    code: int
    stdout: str
    stderr: str


class GitRepo:
    """Small async git wrapper. Always argv, never a shell."""

    def __init__(self, root: Path, git_bin: str = "git") -> None:
        self.root = Path(root)
        self.git_bin = git_bin

    async def _run(
        self,
        args: list[str],
        *,
        cwd: Path | None = None,
        timeout: int = GIT_TIMEOUT,
        check: bool = True,
    ) -> CommandResult:
        argv = [self.git_bin, *args]
        try:
            proc = await asyncio.create_subprocess_exec(
                *argv,
                cwd=str(cwd or self.root),
                stdin=asyncio.subprocess.DEVNULL,
                stdout=asyncio.subprocess.PIPE,
                stderr=asyncio.subprocess.PIPE,
            )
        except OSError as exc:
            raise FreebuffError(f"could not start git: {exc}") from exc
        try:
            stdout_b, stderr_b = await asyncio.wait_for(proc.communicate(), timeout=timeout)
        except asyncio.TimeoutError as exc:
            proc.kill()
            await proc.wait()
            raise FreebuffError(f"git {args[0]} timed out after {timeout}s") from exc
        result = CommandResult(
            proc.returncode,
            stdout_b.decode("utf-8", "replace"),
            stderr_b.decode("utf-8", "replace"),
        )
        if check and result.code != 0:
            detail = (result.stderr or result.stdout).strip()[-2000:]
            raise FreebuffError(f"git {args[0]} failed ({result.code}): {detail}")
        return result

    async def verify_base(self, base: str) -> None:
        base = rules.assert_not_main(base)
        result = await self._run(
            ["rev-parse", "--verify", "--quiet", f"refs/heads/{base}"], check=False
        )
        if result.code != 0:
            raise FreebuffError(
                f"authorized branch {base!r} does not exist in {self.root}; "
                "check out or fetch it first"
            )

    async def branch_exists(self, branch: str) -> bool:
        result = await self._run(
            ["show-ref", "--verify", "--quiet", f"refs/heads/{branch}"], check=False
        )
        return result.code == 0

    async def create_worktree(self, branch: str, path: Path, base: str) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        if path.exists():
            raise FreebuffError(f"worktree path already exists: {path}")
        await self._run(["worktree", "add", "-b", branch, str(path), base])

    async def current_branch(self, cwd: Path) -> str:
        result = await self._run(["symbolic-ref", "--short", "-q", "HEAD"], cwd=cwd, check=False)
        if result.code == 0:
            return result.stdout.strip()
        result = await self._run(["rev-parse", "--short", "HEAD"], cwd=cwd, check=False)
        return result.stdout.strip()

    async def head(self, cwd: Path) -> str:
        result = await self._run(["rev-parse", "HEAD"], cwd=cwd)
        return result.stdout.strip()

    async def stage_all(self, cwd: Path) -> None:
        await self._run(["add", "-A", "--", "."], cwd=cwd)

    async def status(self, cwd: Path) -> str:
        result = await self._run(["status", "--short", "--branch"], cwd=cwd)
        return result.stdout

    async def status_paths(self, cwd: Path) -> list[str]:
        result = await self._run(["status", "--porcelain=v1", "-z"], cwd=cwd)
        parts = result.stdout.split("\0")
        paths: list[str] = []
        index = 0
        while index < len(parts):
            entry = parts[index]
            index += 1
            if not entry:
                continue
            status_code = entry[:2]
            path = entry[3:] if len(entry) > 3 else ""
            if status_code[0] in ("R", "C") or status_code[1] in ("R", "C"):
                # Rename/copy entries carry the old path as the next field.
                # Keep it too: moving a protected file is still touching it.
                old_path = parts[index] if index < len(parts) else ""
                index += 1
                if old_path:
                    paths.append(rules.normalize_path(old_path))
            if path:
                paths.append(rules.normalize_path(path))
        return sorted(set(paths))

    async def numstat(self, cwd: Path, base: str) -> tuple[int, list[tuple[str, int]]]:
        """Return (total changed lines, [(path, changed lines)]) without the diff."""
        result = await self._run(
            ["diff", "--numstat", "--no-color", "--no-ext-diff", base, "--", "."], cwd=cwd
        )
        total = 0
        per_file: list[tuple[str, int]] = []
        for line in result.stdout.splitlines():
            fields = line.split("\t")
            if len(fields) < 3:
                continue
            added, removed, path = fields[0], fields[1], fields[2]
            try:
                changed = int(added) + int(removed)
            except ValueError:
                # Binary files report "-" and have no line counts.
                changed = 0
            total += changed
            per_file.append((rules.normalize_path(path), changed))
        return total, per_file

    async def diff(self, cwd: Path, base: str) -> str:
        result = await self._run(
            ["diff", "--no-color", "--no-ext-diff", base, "--", "."], cwd=cwd
        )
        return result.stdout

    async def signature(self, cwd: Path) -> str:
        """Cheap change detector: HEAD plus the worktree status."""
        head_result = await self._run(["rev-parse", "HEAD"], cwd=cwd)
        head = head_result.stdout.strip()
        status = await self._run(["status", "--porcelain=v1", "-z"], cwd=cwd)
        digest = hashlib.sha256(status.stdout.encode("utf-8", "replace")).hexdigest()
        return f"{head}:{digest}"

    async def snapshot(self, cwd: Path, base: str) -> str:
        """HEAD plus a digest of what a push would carry.

        Written for the Approve path: after staging, `--raw` lists the blob ids
        of every changed path, so an edit made after the review changes the
        digest even when the line count happens to match, and no diff text has
        to be loaded on a small machine.
        """
        await self.stage_all(cwd)
        head = await self.head(cwd)
        result = await self._run(
            [
                "diff",
                "--cached",
                "--raw",
                "--no-renames",
                "--abbrev=40",
                "--no-color",
                "--no-ext-diff",
                base,
                "--",
                ".",
            ],
            cwd=cwd,
        )
        digest = hashlib.sha256(result.stdout.encode("utf-8", "replace")).hexdigest()
        return f"{head}:{digest}"

    async def commit_all(self, cwd: Path, message: str) -> str:
        await self.stage_all(cwd)
        result = await self._run(
            [
                "-c",
                "user.name=Mac Builder Bot",
                "-c",
                "user.email=mac-builder@localhost",
                "commit",
                "-m",
                message,
            ],
            cwd=cwd,
            check=False,
        )
        if result.code != 0:
            detail = (result.stderr or result.stdout).strip()[-2000:]
            raise FreebuffError(f"commit failed ({result.code}): {detail}")
        return await self.head(cwd)

    async def fetch_origin_main(self, remote: str = "origin", branch: str = "main") -> None:
        """Refresh origin/main, so a dan branch never starts from a stale base."""
        result = await self._run(
            ["fetch", "--quiet", remote, branch], timeout=300, check=False
        )
        if result.code != 0:
            detail = (result.stderr or result.stdout).strip()[-1000:]
            raise FreebuffError(
                f"could not fetch {remote} {branch}: {detail or f'exit {result.code}'}"
            )

    async def push_branch(self, cwd: Path, branch: str, *, kind: str = "task") -> None:
        branch = rules.validate_push_branch(branch, kind=kind)
        current = await self.current_branch(cwd)
        if current != branch:
            raise FreebuffError(
                f"refusing to push: worktree is on {current!r}, expected {branch!r}"
            )
        await self._run(
            [
                "push",
                "--porcelain",
                "origin",
                f"refs/heads/{branch}:refs/heads/{branch}",
            ],
            cwd=cwd,
            timeout=300,
        )

    async def remove_worktree(self, path: Path) -> bool:
        """Remove a worktree; log and return False when git refuses.

        A worktree only belongs to the checkout that created it, so a failure
        here (git says "is not a working tree") used to be swallowed with
        check=False and left the directory behind for good.
        """
        result = await self._run(
            ["worktree", "remove", "--force", str(path)], check=False
        )
        if result.code != 0:
            detail = (result.stderr or result.stdout).strip()[-500:] or "no output"
            log.warning(
                "could not remove worktree %s (exit %s): %s", path, result.code, detail
            )
            return False
        await self._run(["worktree", "prune"], check=False)
        return True


def _hint_matches(hint: str, label: str) -> bool:
    """Whether a collapsed question's `↳ "<value>"` line shows this option label.

    Freebuff commits a row on Enter, collapses the question and draws the value
    it took as `↳ "Formal"`, so that line is the confirmation for an option.
    """
    def norm(text: str) -> str:
        return " ".join(text.strip().strip("\"'\u201c\u201d\u2018\u2019").split()).casefold()

    return bool(hint) and norm(hint) == norm(label)


def _arrow_keys(start: int | None, target: int) -> list[str]:
    """Arrow presses that take the focus from `start` to `target`."""
    if start is None or start == target:
        return []
    delta = target - start
    return ["Down"] * delta if delta > 0 else ["Up"] * (-delta)


_SGR_RE = re.compile(r"\x1b\[([0-9;:]*)m")


def styled_submit_focus(styled: str) -> bool | None:
    """Whether the Submit button is drawn focused in a `capture-pane -e` capture.

    Freebuff draws the focused Submit in bold (ESC[1m) and the unfocused one in
    plain grey, both inside a box whose plain text is identical, so the colour
    codes are the only evidence. None: no Submit row, or nothing to go on.
    """
    for line in styled.splitlines():
        at = line.find("Submit")
        if at < 0:
            continue
        bold = False
        for match in _SGR_RE.finditer(line[:at]):
            params = [part for part in re.split(r"[;:]", match.group(1))]
            index = 0
            while index < len(params):
                code = params[index] or "0"
                if code in ("38", "48"):
                    # 38;2;r;g;b or 38;5;n: the numbers after it are a colour
                    index += 4 if index + 1 < len(params) and params[index + 1] == "2" else 2
                    continue
                if code == "0":
                    bold = False
                elif code == "1":
                    bold = True
                elif code == "22":
                    bold = False
                index += 1
        return bold
    return None


class FreebuffRunner:
    """Supervises the Freebuff process for one job at a time."""

    def __init__(self, settings: object) -> None:
        self.settings = settings
        self.repo_dir = Path(getattr(settings, "repo_dir"))
        self.worktree_root = Path(getattr(settings, "worktree_root"))
        self.git_bin = shutil.which("git") or "/usr/bin/git"
        self.tmux_bin = shutil.which("tmux") or "/opt/homebrew/bin/tmux"
        self.repo = GitRepo(self.repo_dir, self.git_bin)
        self._self_git: GitRepo | None = None
        self._active: TaskEnvironment | None = None
        # The one question open right now, and the future /answer resolves.
        self._question: questions.Question | None = None
        self._answer_future: asyncio.Future[str] | None = None
        # Boxes already driven to Submit, so one that lingers is not asked twice,
        # and the last titled box that did not parse (posted once, never idled).
        self._handled_boxes: set[str] = set()
        self._broken_box = ""
        # The screen the job is waiting on, which session it belongs to, and the
        # sinks /screen, /key and /send act through. The job runner installs the
        # reporter, so nothing here needs Discord.
        self._screen: screens.Screen | None = None
        self._screen_session: str | None = None
        self._screen_log: Path | None = None
        self._screen_reporter: Callable[[screens.Screen, str], Awaitable[None]] | None = None
        # Screens already posted, so a static pane is shown once, not per poll.
        self._screens_seen: set[str] = set()
        # Why the session exited, and what the last stall was, for the report.
        self._exit_note = ""
        self._last_stall_kind = ""
        # The tmux server inherits this environment, so the builder never sees
        # the bot's Discord or manager credentials. Everything else (PATH,
        # SSH_AUTH_SOCK, Freebuff's own configuration) is preserved.
        self._tmux_environment = {
            key: value
            for key, value in os.environ.items()
            if key != "DISCORD_TOKEN" and not key.startswith("MANAGER_")
        }

    @property
    def active(self) -> TaskEnvironment | None:
        return self._active

    def _freebuff_argv(self) -> list[str]:
        raw_bin = str(getattr(self.settings, "freebuff_bin")).strip() or "freebuff"
        resolved = raw_bin
        if "/" in raw_bin:
            if not Path(raw_bin).is_file():
                raise FreebuffError(f"FREEBUFF_BIN does not exist: {raw_bin}")
        else:
            found = shutil.which(raw_bin)
            if not found:
                raise FreebuffError(
                    f"FREEBUFF_BIN {raw_bin!r} was not found on PATH; install the "
                    "Freebuff CLI or point FREEBUFF_BIN at it"
                )
            resolved = found
        extra = getattr(self.settings, "freebuff_args", []) or []
        return [resolved, *extra]

    async def _tmux(self, *args: str, input_bytes: bytes | None = None) -> CommandResult:
        # A dedicated socket keeps the bot's sessions apart from the user's own
        # tmux and guarantees the server starts with the sanitised environment.
        argv = [self.tmux_bin, "-L", TMUX_SOCKET, *args]
        proc = await asyncio.create_subprocess_exec(
            *argv,
            env=self._tmux_environment,
            stdin=asyncio.subprocess.PIPE if input_bytes is not None else asyncio.subprocess.DEVNULL,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
        )
        try:
            stdout_b, stderr_b = await asyncio.wait_for(
                proc.communicate(input_bytes), timeout=TMUX_TIMEOUT
            )
        except asyncio.TimeoutError as exc:
            proc.kill()
            await proc.wait()
            raise FreebuffError(f"tmux {args[0]} timed out") from exc
        return CommandResult(
            proc.returncode,
            stdout_b.decode("utf-8", "replace"),
            stderr_b.decode("utf-8", "replace"),
        )

    async def _session_alive(self, session: str) -> bool:
        result = await self._tmux("has-session", "-t", session)
        return result.code == 0

    def _append_log(self, log_path: Path, text: str) -> None:
        log_path.parent.mkdir(parents=True, exist_ok=True)
        with log_path.open("a", encoding="utf-8", errors="replace") as handle:
            handle.write(text)
            if not text.endswith("\n"):
                handle.write("\n")
            handle.flush()

    def _write_push_guard(
        self, job_id: str, *, prefix: str = rules.TASK_BRANCH_PREFIX
    ) -> Path:
        guard_dir = self.worktree_root / f".guard-{job_id}" / "bin"
        guard_dir.mkdir(parents=True, exist_ok=True)
        script = guard_dir / "git"
        script.write_text(
            PUSH_GUARD_TEMPLATE.replace("__REAL_GIT__", shlex.quote(self.git_bin)).replace(
                "__ALLOWED_PREFIX__", prefix
            ),
            encoding="utf-8",
        )
        script.chmod(0o755)
        return guard_dir.parent

    def _self_root(self) -> Path:
        """The checkout that holds her own code, i.e. mac-builder/."""
        ctx = getattr(self.settings, "project", None)
        self_dir = getattr(ctx, "self_dir", None) if ctx is not None else None
        return Path(self_dir) if self_dir else self.repo_dir

    @property
    def self_repo(self) -> GitRepo:
        root = self._self_root()
        if self._self_git is None or self._self_git.root != root:
            self._self_git = GitRepo(root, self.git_bin)
        return self._self_git

    def _repo_for(self, env: TaskEnvironment | None) -> GitRepo:
        """The checkout a job's worktree belongs to.

        A dan worktree is created in her own checkout, so its removal has to run
        against self_repo; anything else uses the target checkout.
        """
        return self.self_repo if env is not None and env.kind == "dan" else self.repo

    async def start_task(
        self, *, job_id: str, task_text: str, log_path: Path, kind: str = "task"
    ) -> TaskEnvironment:
        if kind == "dan":
            return await self._start_dan_task(
                job_id=job_id, task_text=task_text, log_path=log_path
            )
        base = rules.assert_not_main(str(getattr(self.settings, "authorized_branch")))
        await self.repo.verify_base(base)
        if not Path(self.tmux_bin).is_file():
            raise FreebuffError(f"tmux not found at {self.tmux_bin}; install tmux")
        freebuff_argv = self._freebuff_argv()

        branch = ""
        for _ in range(6):
            candidate = f"{rules.TASK_BRANCH_PREFIX}{secrets.token_hex(4)}"
            if not await self.repo.branch_exists(candidate):
                branch = candidate
                break
        if not branch:
            raise FreebuffError("could not allocate a unique freebuff/* branch")

        worktree = self.worktree_root / job_id
        await self.repo.create_worktree(branch, worktree, base)
        guard_root = self._write_push_guard(job_id)
        session = f"macbuilder-{job_id[-8:]}"
        env = TaskEnvironment(
            branch=branch,
            worktree=worktree,
            session=session,
            base_branch=base,
            guard_dir=guard_root,
        )
        self._append_log(
            log_path,
            f"\n=== Freebuff task ===\nbranch: {branch}\nworktree: {worktree}\nbase: {base}\n",
        )
        await self._launch(env, freebuff_argv, task_text, log_path)
        return env

    async def _start_dan_task(
        self, *, job_id: str, task_text: str, log_path: Path
    ) -> TaskEnvironment:
        """A self-build: her own checkout, dan/<job id>, from a fresh origin/main.

        The base is origin/main after a fetch, not the local main, which may be
        stale or missing. Nothing is ever pushed *to* main, and the push guard
        for this worktree allows dan/* only.
        """
        repo = self.self_repo
        await repo.fetch_origin_main()
        if not Path(self.tmux_bin).is_file():
            raise FreebuffError(f"tmux not found at {self.tmux_bin}; install tmux")
        freebuff_argv = self._freebuff_argv()

        branch = f"{rules.DAN_BRANCH_PREFIX}{job_id}"
        if not rules.is_dan_branch(branch):
            raise FreebuffError(f"refusing to create branch {branch!r}")
        if await repo.branch_exists(branch):
            raise FreebuffError(f"dan branch already exists: {branch}")

        base = DAN_BASE_BRANCH
        worktree = self.worktree_root / job_id
        await repo.create_worktree(branch, worktree, base)
        guard_root = self._write_push_guard(job_id, prefix=rules.DAN_BRANCH_PREFIX)
        env = TaskEnvironment(
            branch=branch,
            worktree=worktree,
            session=f"macbuilder-{job_id[-8:]}",
            base_branch=base,
            guard_dir=guard_root,
            kind="dan",
        )
        self._append_log(
            log_path,
            f"\n=== Dan self-build ===\nrepo: {repo.root}\nbranch: {branch}\n"
            f"worktree: {worktree}\nbase: {base} (just fetched)\n",
        )
        await self._launch(env, freebuff_argv, task_text, log_path)
        return env

    async def _launch(
        self,
        env: TaskEnvironment,
        freebuff_argv: list[str],
        task_text: str,
        log_path: Path,
    ) -> None:
        try:
            await self._start_session(env, freebuff_argv, log_path)
            env.signature_at_start = await self.repo.signature(env.worktree)
            self._append_log(
                log_path,
                "\n--- task sent to Freebuff ---\n" + task_text + "\n--- end task ---\n",
            )
            await self._send_text(env.session, task_text)
        except Exception:
            await self.abort(env)
            raise
        self._active = env

    async def _start_session(
        self, env: TaskEnvironment, freebuff_argv: list[str], log_path: Path
    ) -> None:
        if await self._session_alive(env.session):
            await self._tmux("kill-session", "-t", env.session)
        path_with_guard = str(env.guard_dir / "bin") if env.guard_dir else ""
        original_path = os.environ.get("PATH", "/usr/bin:/bin")
        session_path = f"{path_with_guard}:{original_path}" if path_with_guard else original_path
        argv = [
            "new-session",
            "-d",
            "-s",
            env.session,
            "-c",
            str(env.worktree),
            "-e",
            f"PATH={session_path}",
            "--",
            *freebuff_argv,
        ]
        result = await self._tmux(*argv)
        if result.code != 0:
            raise FreebuffError(f"could not start tmux session: {result.stderr.strip()}")
        pipe = await self._tmux(
            "pipe-pane",
            "-o",
            "-t",
            env.session,
            "cat >> " + shlex.quote(str(log_path)),
        )
        if pipe.code != 0:
            raise FreebuffError(f"could not capture tmux output: {pipe.stderr.strip()}")
        await self._wait_ready(env, log_path)

    async def _wait_ready(
        self, env: TaskEnvironment, log_path: Path | None = None
    ) -> None:
        """Wait until the task text may be typed into what is on screen.

        Any output at all used to count as ready, so a sign-in screen received
        the whole task. Now a screen a person has to deal with is posted to
        Discord instead: the task is sent only once that screen is gone, the
        owner is asked once per distinct screen, and the wait is capped like a
        question so nothing hangs silently.
        """
        ready_seconds = float(getattr(self.settings, "freebuff_ready_seconds"))
        cap = max(1.0, float(getattr(self.settings, "question_wait_seconds", 1800.0)))
        deadline = time.monotonic() + ready_seconds
        seen: dict[str, float] = {}
        reported = ""
        while True:
            now = time.monotonic()
            if not await self._session_alive(env.session):
                raise FreebuffError(
                    "Freebuff exited before it was ready; see the job log"
                )
            pane = await self._pane(env.session)
            if pane.strip():
                screen = screens.classify(pane)
                if screen.kind not in screens.WAITING_KINDS:
                    self._screen = None
                    self._screen_session = None
                    return
                if screen.kind == screens.SURVEY:
                    # Freebuff's own popup is dismissed, never forwarded, and
                    # never allowed to hold up the task text.
                    if log_path is not None:
                        self._append_log(
                            log_path,
                            "\n[survey popup dismissed with Esc before the task]\n",
                        )
                    await self._dismiss(env.session, log_path)
                    continue
                if screen.key != reported:
                    reported = screen.key
                    seen.setdefault(screen.key, now + cap)
                    self._screen = screen
                    self._screen_session = env.session
                    self._screen_log = log_path
                    if log_path is not None:
                        await self._report_screen(
                            screen, log_path, "before the task was sent"
                        )
                if now >= seen.get(screen.key, now + cap):
                    raise FreebuffError(
                        f"Freebuff stayed on {screens.describe(screen.kind)} and never "
                        f"took the task text, so nothing was typed. {_KEY_HINT}"
                    )
                # Waiting for a person is not readiness time.
                deadline = max(deadline, now + ready_seconds)
            elif now >= deadline:
                raise FreebuffError(
                    f"Freebuff produced no output within {ready_seconds}s"
                )
            if now >= deadline:
                raise FreebuffError(
                    f"Freebuff produced no output within {ready_seconds}s"
                )
            await asyncio.sleep(READY_POLL_SECONDS)

    async def _send_text(self, session: str, text: str) -> None:
        loaded = await self._tmux(
            "load-buffer", "-b", "macbuilder", "-", input_bytes=text.encode("utf-8")
        )
        if loaded.code != 0:
            raise FreebuffError(f"could not load task text into tmux: {loaded.stderr.strip()}")
        pasted = await self._tmux(
            "paste-buffer", "-d", "-b", "macbuilder", "-t", session
        )
        if pasted.code != 0:
            raise FreebuffError(f"could not paste task text into Freebuff: {pasted.stderr.strip()}")
        sent = await self._tmux("send-keys", "-t", session, "Enter")
        if sent.code != 0:
            raise FreebuffError(f"could not submit task text: {sent.stderr.strip()}")

    async def _pane(self, session: str) -> str:
        """The visible pane, read only for question detection."""
        result = await self._tmux(
            "capture-pane", "-p", "-J", "-t", session, "-S", f"-{PANE_LINES}"
        )
        return result.stdout if result.code == 0 else ""

    async def _log_styled_submit(
        self, session: str, key: str, log_path: Path
    ) -> None:
        """QUESTION_DEBUG only: the Submit rows with their colour codes visible.

        The plain capture cannot show which button has the focus when that is
        only a colour. ESC is written as `<ESC>` so the codes survive in the log.
        """
        result = await self._tmux(
            "capture-pane", "-e", "-p", "-J", "-t", session, "-S", f"-{PANE_LINES}"
        )
        if result.code != 0:
            return
        lines = result.stdout.splitlines()
        keep: list[str] = []
        for index, line in enumerate(lines):
            if "Submit" in line:
                for near in lines[max(0, index - 1) : index + 2]:
                    if near not in keep:
                        keep.append(near)
        if not keep:
            return
        styled = "\n".join(keep).replace("\x1b", "<ESC>")
        self._append_log(
            log_path,
            f"\n[styled Submit rows after {key}]\n"
            f"{questions.redact(styled[-DEBUG_PANE_CHARS:])}\n",
        )

    async def _styled_pane(self, session: str) -> str | None:
        """The pane with colour codes, for the one thing plain text cannot show."""
        result = await self._tmux(
            "capture-pane", "-e", "-p", "-J", "-t", session, "-S", f"-{PANE_LINES}"
        )
        return result.stdout if result.code == 0 else None

    async def _submit_focus(
        self, session: str, box: questions.QuestionBox
    ) -> bool | None:
        """Whether Submit has the focus: the colour codes first, the text marker after."""
        styled = await self._styled_pane(session)
        if styled:
            focus = styled_submit_focus(styled)
            if focus is not None:
                return focus
        return box.submit_focused

